@dataclass(frozen=True)
class SettingDefinition:
    key: str
    label: str
    category: str
    value_type: str
    default: Any
    description: str
    env_name: Optional[str] = None
    unit: str = ""
    apply_mode: str = "immediate"
    min_value: Any = None
    max_value: Any = None
    choices: Tuple[Any, ...] = ()
    secret: bool = False
    dangerous: bool = False
    advanced: bool = False
    mutable: bool = True


def _setting(
    key: str,
    label: str,
    category: str,
    value_type: str,
    default: Any,
    description: str,
    **kwargs,
) -> SettingDefinition:
    return SettingDefinition(
        key=key,
        label=label,
        category=category,
        value_type=value_type,
        default=default,
        description=description,
        **kwargs,
    )


