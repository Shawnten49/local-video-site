DEFINITIONS_BY_KEY: Dict[str, SettingDefinition] = {
    item.key: item for item in SETTING_DEFINITIONS
}

_ENV_NAMES = [
    item.env_name for item in SETTING_DEFINITIONS if item.env_name
]
if len(DEFINITIONS_BY_KEY) != len(SETTING_DEFINITIONS):
    raise RuntimeError("Duplicate setting key")
if len(set(_ENV_NAMES)) != len(_ENV_NAMES):
    raise RuntimeError("Duplicate setting environment variable")


def parse_value(value_type: str, raw: Any) -> Any:
    if value_type == "bool":
        if isinstance(raw, bool):
            return raw
        text = str(raw).strip().lower()
        if text in {"1", "true", "yes", "on"}:
            return True
        if text in {"0", "false", "no", "off"}:
            return False
        raise ValueError("布尔值必须是 true/false 或 1/0")
    if value_type == "int":
        if isinstance(raw, bool):
            raise ValueError("必须是整数")
        return int(raw)
    if value_type == "float":
        if isinstance(raw, bool):
            raise ValueError("必须是数字")
        return float(raw)
    if value_type in {"bytes", "secret"}:
        if value_type == "secret":
            return None
        if isinstance(raw, bool):
            raise ValueError("必须是字节数")
        return int(raw)
    if value_type == "enum":
        return str(raw or "").strip()
    return str(raw if raw is not None else "").strip()


def validate_value(definition: SettingDefinition, value: Any) -> Any:
    parsed = parse_value(definition.value_type, value)
    if definition.value_type == "enum":
        if parsed not in definition.choices:
            matches = {
                str(choice).casefold(): choice
                for choice in definition.choices
            }
            parsed = matches.get(parsed.casefold(), parsed)
        if parsed not in definition.choices:
            raise ValueError(
                "必须是以下值之一: {}".format(
                    ", ".join(definition.choices)
                )
            )
    if definition.min_value is not None and parsed < definition.min_value:
        raise ValueError("不能小于 {}".format(definition.min_value))
    if definition.max_value is not None and parsed > definition.max_value:
        raise ValueError("不能大于 {}".format(definition.max_value))
    return parsed


def iter_definitions(
    category: str = "",
    query: str = "",
    include_advanced: bool = True,
) -> Iterable[SettingDefinition]:
    needle = str(query or "").strip().casefold()
    for item in SETTING_DEFINITIONS:
        if category and item.category != category:
            continue
        if not include_advanced and item.advanced:
            continue
        haystack = " ".join(
            (item.key, item.label, item.description)
        ).casefold()
        if needle and needle not in haystack:
            continue
        yield item
